use licencify::config::Config;
use std::fs;
use std::path::Path;

#[test]
fn schema_file_matches_example() {
    let committed_path = Path::new(env!("CARGO_MANIFEST_DIR")).join("schema/config.json");
    let committed = fs::read_to_string(&committed_path).unwrap_or_else(|err| {
        panic!(
            "failed to read committed schema at {}: {err}; run cargo run --example schema",
            committed_path.display()
        )
    });
    let committed_val: serde_json::Value = serde_json::from_str(&committed).unwrap_or_else(|err| {
        panic!("committed schema at {} is not valid JSON: {err}", committed_path.display())
    });
    let generated = Config::schema_json().expect("Failed to serialize schema");
    let generated_val: serde_json::Value =
        serde_json::from_str(&generated).expect("generated schema must be valid JSON");

    assert_eq!(
        committed_val,
        generated_val,
        "schema/config.json has drifted from the schema generated by the example; run `cargo run --example schema` to regenerate"
    );
}

#[test]
fn schema_describes_settable_keys_and_not_legacy_keys() {
    let generated = Config::schema_json().expect("Failed to serialize schema");
    let schema: serde_json::Value =
        serde_json::from_str(&generated).expect("schema must be valid JSON");

    let defs = schema
        .get("$defs")
        .expect("schema should contain $defs definitions");

    let default_props = defs
        .get("DefaultConfig")
        .and_then(|d| d.get("properties"))
        .expect("DefaultConfig properties");

    for key in [
        "author",
        "company",
        "email",
        "licence",
        "format",
        "year",
        "basename",
        "update-readme",
        "update-manifest",
        "additional-licences",
    ] {
        assert!(
            default_props.get(key).is_some(),
            "DefaultConfig must describe key `{key}`"
        );
    }

    let subdir_props = defs
        .get("SubdirConfig")
        .and_then(|d| d.get("properties"))
        .expect("SubdirConfig properties");

    for key in [
        "path",
        "author",
        "company",
        "email",
        "licence",
        "format",
        "year",
        "basename",
        "update-readme",
        "update-manifest",
        "additional-licences",
    ] {
        assert!(
            subdir_props.get(key).is_some(),
            "SubdirConfig must describe key `{key}`"
        );
    }

    let schema_str = generated.to_lowercase();
    assert!(
        !schema_str.contains("licence_file_name"),
        "schema must not describe licence_file_name"
    );
    assert!(
        !schema_str.contains("license_file_name"),
        "schema must not describe license_file_name"
    );
    assert!(
        !schema_str.contains("licence_name"),
        "schema must not describe licence_name"
    );
    assert!(
        !schema_str.contains("license_name"),
        "schema must not describe license_name"
    );
}
